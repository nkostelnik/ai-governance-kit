"""Stage 5: the decision memo. A short markdown record a business owner and
counsel can read and sign. Everything in it comes from the register entry;
nothing is generated by a model.
"""

from .register import ToolEntry, UseCaseEntry
from .rubric import Rubric, Tier, load_rubric

STATUS_TEXT = {
    "provisional": "PROVISIONAL: open questions must be answered before this can be approved.",
    "awaiting_signoff": "Awaiting sign-off.",
    "approved": "Approved.",
    "prohibited": "Prohibited. Do not proceed unless an exception is granted.",
    "exception_granted": "Prohibited use permitted by exception.",
    "reassessment_required": "Reassessment required before continued use.",
}


def cell(text: str | None) -> str:
    return (text or "").replace("|", "/").replace("\n", " ")


def phrase(text: str) -> str:
    """A rubric description used mid-sentence: no trailing period."""
    return text.strip().rstrip(".")


def render_memo(entry: UseCaseEntry, tool: ToolEntry | None = None, rubric: Rubric | None = None) -> str:
    rubric = rubric or load_rubric()
    r = entry.result
    out = [
        f"# AI use-case decision memo: {entry.name}",
        "",
        f"> **{r.disclaimer}**",
        "",
        f"| | |\n|---|---|\n| Record | {entry.id} |\n| Business owner | {cell(entry.owner) or 'not stated'} |"
        f"\n| Department | {cell(entry.department) or 'not stated'} |\n| Tool | {tool.name if tool else 'not registered'} |"
        f"\n| Risk tier | **{r.tier.value}** |\n| Status | {STATUS_TEXT[entry.status]} |",
        "",
        "## Why this tier",
        "",
        *[f"- {cell(reason)}" for reason in r.reasons],
        "",
        "## Facts relied on",
        "",
        "| Dimension | Rating | Basis | Supporting text |",
        "|---|---|---|---|",
    ]
    for rating in r.ratings:
        dim = rubric.dimension(rating.dimension_id)
        if rating.source == "unknown":
            out.append(f"| {dim.name} | {rating.tier.value} | unknown | Not established; see open questions |")
            continue
        level = phrase(dim.level(rating.driver_level).description)
        basis = rating.driver_basis + (", approved-tool tier" if rating.approved_tool_applied else "")
        out.append(f"| {dim.name} | {rating.tier.value} | {basis} | {cell(level)}: \"{cell(rating.driver_quote)}\" |")

    if entry.strikes:
        out += ["", "## Reviewer corrections", ""]
        out += [f"- Struck {s.dimension_id}.{s.level_id} (\"{cell(s.quote)}\"): {cell(s.reason)} "
                f"({s.by}, {s.role}, {s.on})" for s in entry.strikes]

    if r.tier == Tier.Prohibited:
        out += ["", "## Exception path", "", f"- {r.prohibited_exception or 'No exceptions allowed.'}"]
    else:
        out += ["", "## Required controls", ""]
        out += [f"- **{c.id}**: {c.description} ({c.why})" for c in r.controls]

    if r.regulatory_flags:
        out += ["", "## Laws to check (not legal conclusions)", ""]
        out += [f"- {f.topic}. {f.citation} (matched: {', '.join(f.matched)})" for f in r.regulatory_flags]

    if r.open_questions or r.needs_review:
        out += ["", "## Open items", ""]
        out += [f"- Question: {q.question}" for q in r.open_questions]
        out += [f"- Review: {cell(n)}" for n in r.needs_review]

    out += ["", "## Tool and vendor", ""]
    if tool:
        out.append(f"- {tool.name} ({tool.vendor}). Vendor handling: {tool.confirmed_level or 'not confirmed'}"
                   f" (proposed by review: {tool.proposed_level}). Listed as approved: {'yes' if tool.listed_as_approved else 'no'}.")
        if tool.blockers:
            out.append(f"- Open must-have gaps: {', '.join(tool.blockers)}.")
        if tool.flags:
            out.append(f"- Negotiation flags: {', '.join(tool.flags)}.")
    else:
        out.append("- No register record: vendor terms are treated as unreviewed.")

    out += ["", "## Review", ""]
    if entry.next_review:
        out.append(f"- Next scheduled review: {entry.next_review}.")
    elif r.review_cadence_months:
        out.append(f"- Review every {r.review_cadence_months} months from approval.")
    out.append("- Reassess sooner if any of these occur: "
               + "; ".join(phrase(t) for t in rubric.review.reassessment_triggers.values()) + ".")
    if entry.pending_triggers:
        out.append(f"- **Pending triggers: {', '.join(entry.pending_triggers)}.**")

    signers = entry.required_signers() if r.tier != Tier.Prohibited else (
        rubric.approvers.prohibited_exception.joint_approval if entry.status == "exception_granted" else [])
    if signers:
        signed = {s.role: s for s in entry.signoffs}
        out += ["", "## Sign-off", "", "| Role | Name | Date |", "|---|---|---|"]
        for role in signers:
            s = signed.get(role)
            out.append(f"| {phrase(rubric.approvers.catalog.get(role, role))} | {s.name if s else '________________'} "
                       f"| {s.on if s else '__________'} |")

    out += ["", "---", f"Assessed against rubric sha256 {entry.rubric_sha256[:12]}. {r.disclaimer}", ""]
    return "\n".join(out)
